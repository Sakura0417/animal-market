import type { LevelConfig } from './Types';
import { ENABLE_FARM_ROCKS } from './Constants';

/** 关卡配置（2026-09-06 09:30:00 难度外环）：
 * L1-12 保持原验证曲线不动（种子对拍 12/12 依赖该路径）；L13 起原先与 L12 完全同质，
 * 现按用户要求逐级加压——种类数解锁到 6（L13+）、单订单最多 4 种（L15+）、石头 4 颗
 * （L20+）：围栏/车位压力显著上升，后期需要看广告解锁车位/复活才能稳定通关。
 *
 * 2026-09-07 22:38：石头数量统一受 Constants.ENABLE_FARM_ROCKS 开关闸门控制
 * （默认 false ⇒ 全关卡 rocks = 0，农场不生成石头；置 true ⇒ 完全恢复下列原曲线）。
 * 数量公式本身未做任何改动，开关只决定是否套用。
 *
 * 2026-09-07 23:30：herdN 公式 L4-L12 各 +8（去石+对冲修复后难度补偿），同时取消原 L9-12 的
 * -2 修正（0 石场景下无需抑挤爆率）。L1-L3 保留原值（教学关保护）。
 * 终态 L4=24 / L5=26 / L6=28 / L7-L12=30（触顶）。
 *
 * 2026-09-09 23:35 P1.5 紧密化（docs/grid-scheme-review-20260909.md）：
 *   - tightness 盘面紧密度：L1-3=0.25（教学关仍偏疏松）→ L4-7=0.55 → L8-12=0.85 → L13+=1（纯团簇）。
 *     依据：cluster n=30 被挡率 61% vs 均匀 34%（探针实测），落实 PRD 5.1「紧密排列」。
 *   - pressure 朝向反向偏置：L1-3=0（朝场外好上手）→ L4-7=0.35 → L8-12=0.6 → L13+=0.8。
 *     依据：PRD 5.1 明文「高关卡反向偏置制造链条」（此前从未实现）。
 *   - 终值以 BalanceSim 扫参为准（DEVLOG 2026-09-09 记录调参过程）。 */
export function levelCfg(n: number): LevelConfig {
  n = Math.max(1, Math.min(30, n | 0));
  return {
    level: n,
    // 动物数量随关卡递增（2026-09-06 13:32:00）：L1-14 封顶 30（对拍保护区不变），
    //   L15-19 32 只、L20+ 34 只——农场缩小后按关卡逐步加压。
    //   T1 调参轮 3（2026-09-06 20:20）：L9-12 各 −2 只（挤爆率 50-65% → 目标带内）。
    // 2026-09-07 23:30 需求 #4：去石头 + 对冲修复后整体偏松，对 L4-L12 各 +8 补难度；
    //   L1-3 保留原值（教学关保护），L7-L12 触顶 30。原 L9-12 的 −2 修正（当时为抑挤爆率）
    //   在 0 石头场景下不再需要（已无岩石作挤爆源头），故同步取消。
    // 2026-09-10 19:17 走廊遮挡语义：L7-12 触顶由 30 降到 28（挤爆率 46-48% 偏高，
    //   直接减总量是最有效杠杆）→ L7-12 一审回到 55-75% 带内。
    herdN: Math.min(n <= 12 ? 28 : n <= 14 ? 30 : n <= 19 ? 32 : 34, 8 + n * 2 + (n >= 4 ? 8 : 0)),
    typeCount: n <= 2 ? 3 : n <= 5 ? 4 : n <= 12 ? 5 : 6,
    // 石头（T1 轮 3）：L12 起第 4 颗（与 L11 区隔，n<12 维持 ≤3 保护 L1-11）
    // 2026-09-07 22:38：套用 ENABLE_FARM_ROCKS 开关——关闭时全关卡为 0（农场不随机生成石头）；
    //   开启时完全沿用原曲线表达式，规则与落位逻辑零改动。
    rocks: !ENABLE_FARM_ROCKS ? 0 : (n <= 2 ? 0 : Math.min(n < 12 ? 3 : 4, 1 + ((n - 3) >> 1))),
    rareP: Math.min(.1, .03 + n * .005),
    // 订单种类数（2026-09-06 20:20 T1 调参轮 2）：收购 ≥2+偶数化使订单系统性变大，
    // L8-12 挤爆率升至 52-72%、一审跌至 26-47%（目标带 55-75%）。L4-12 降到 2 种
    // 订单以回落围栏压力；L13-19 3 种、L20+ 4 种保持后期加压梯度。L1-3 维持 1 种
    // （教学关保护，宁简勿难）。
    // 2026-09-07 23:40 D8 调参轮：L6-19 由 2 种提到 3 种（去石+对冲修复后一审 93-96% 全程越上界，
    //   靠"订单更难凑齐"制造围栏压力）；L4-5 保留 2 种（L4-L5 一审 99%+ 需保持平缓爬升）。
    // 2026-09-10 19:17 走廊遮挡语义下回调：L6-19 由 3 种降回 2 种——走廊语义下"移走一只
    //   未必解锁身后那只"（身后者可能仍被更远动物堵着），供给周转率下降、围栏压力结构性上升，
    //   故回到减少订单种类（D8 轮的两条杠杆之一）把一审拉回 55-75% 带。
    orderKinds: n <= 3 ? 1 : n <= 5 ? 2 : n <= 19 ? 2 : 3,
    // 紧密度 / 朝向偏置分级（P1.5，见文件头注释；2026-09-10 19:17 走廊遮挡语义下回调）：
    //   走廊语义（沿朝向路径有占用者即被挡）比相邻格更严：被挡率 60.9% → 70.3%，
    //   可入栏数 11.8 → 8.9 只 ⇒ L6-12 一审跌至 42.5-54%（低于 55-75% 带）。
    //   紧密度是"可动通道数"的直接杠杆（团簇越松、走廊越易清空）故下调：
    //   ⚠️ 实测紧密度对走廊语义难度影响可忽略（L8: 0.85→0.6 仅 +0.2pt），故保留 P1.5 紧凑分级；
    //   真正杠杆是订单压力（orderKinds 2 / ORDER_QTY3_P 0.25）与 herdN（L7-12 触顶 28）。
    tightness: n <= 3 ? 0.25 : n <= 7 ? 0.55 : n <= 12 ? 0.85 : 1,
    pressure: n <= 3 ? 0 : n <= 7 ? 0.35 : n <= 12 ? 0.6 : 0.8,
    
  };
}
