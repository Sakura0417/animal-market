/** 单个广告位失败后的冷却时长（ms）。
 *  官方实测：出现 1004 后反复 `load()` 永远拉不到，必须 `destroy()` + 重建
 *  （或等待一段时间）才能恢复。冷却 + 重建双管齐下，避免在一个已空转的 ID 上
 *  连续浪费玩家的点击。 */
export const AD_RETRY_COOLDOWN_MS = 30_000;

/** 展示中断兜底：广告回调若始终不来（极端机型 / 组件异常），超时释放防重入锁，
 *  并按"未成交"结算（不发奖）。
 *  ⚠️ 锁泄漏会让广告功能整体失效（项目已有 busy 泄漏血案），故必须设超时。 */
export const AD_WATCHDOG_MS = 90_000;

/** 广告类型（小游戏官方支持形态）。
 *  本次只落地 `rewarded`（激励视频）；banner / 插屏的扩展位置见 PlatformAdapter 文件头。 */
export type AdKind = 'rewarded' | 'banner' | 'interstitial';
