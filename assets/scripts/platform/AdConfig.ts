/* 广告位配置（PLATFORM · 2026-09-19 新增）：平台侧的广告位 ID 池与重试策略。
 *
 * 修改时间：2026-10-07 23:34（**多渠道分发地基**）—— 广告位池由单平台一维数组
 *   （`REWARDED_AD_UNITS`）升级为**按平台分池**（`AD_UNITS`）。根因：广告位 ID 是各家
 *   后台签发的**平台级凭证、互不通用**（微信 `adunit-xxx` / 抖音另一套 / 支付宝 `spaceCode`），
 *   单池结构在多渠道下发时必然张冠李戴——把微信 ID 拿去建抖音实例只会得到
 *   1002「广告单元无效」。同时新增 `PlatformKey` 作为 platform 层的统一平台键，
 *   供适配层注册表寻址（见 PlatformAdapter.detectMiniGameHost）。
 *
 * 为什么独立成文件：
 *   ① 广告位 ID 是**平台配置**（在 mp.weixin.qq.com 流量主后台创建），不是业务概念——
 *      放 platform 层，PlatformAdapter 直接读取，依赖方向保持 services → platform 单向；
 *   ② 上线换 ID / 加 ID 只改这一处；点位的业务标识在 `services/AdPoints.ts`。
 *
 * 🟥 开通前置门槛（**官方现行口径，2026-10-07 复核修正**）：
 *   微信流量主满足以下**任一**条件即可（官方页：商业能力 → 广告变现 → 广告开通）：
 *     条件一：小程序累计独立访客 **UV > 500** + 无刷粉行为 + 未曾有严重违规记录（最常见路径）；
 *     条件二：开通内置游戏圈并产生有效活跃 + 发布官方帖 5 篇；
 *     条件三：同主体名下已有小程序已开通流量主、持续一个季度有变现 → 当前小程序可直接开通。
 *   ⚠️ 本文件旧记录写的「UV ≥ 1000」**已过期**，实际门槛是 **500**（勿再按 1000 排期）。
 *   ⚠️ 资格**次日刷新**：达标当天开不了属正常，次日再试。
 *   达标后：mp.weixin.qq.com → 流量主 → 广告位管理 → 新建「激励视频」广告位，复制广告位 ID。
 *   未开通 ⇒ 本池为空 ⇒ 适配层返回 'unavailable'（不发奖、不报错、给提示），
 *   游戏全流程仍可正常试玩（含演示广告层）。
 */

/** 🟥 广告总开关（2026-09-19 新增，**默认关闭**）。
 *
 * 语义（用户需求：「默认关闭，页面不显示任何与广告相关的元素；但看广告所需的相关功能
 * 应可直接使用，不因开关关闭而缺失」）：
 *   - `false`（默认）：**全链路无广告** ——
 *       ① 不创建任何 wx 广告实例、不走演示层；
 *       ② 页面不渲染任何广告元素（道具/车位的视频角标、" · 看广告"按钮后缀、演示广告层）；
 *       ③ 广告点位调用**直接发放奖励** —— 吊车 / 转身 / 挪窝 / 车位解锁 / 围栏放生 /
 *          原地续局 / 营收翻倍全部照常可用，**不因关闭而缺失任何玩法**。
 *     适用：未开通流量主、审核期、以及任何不希望出现广告的调试场合。
 *   - `true`：启用激励视频（**当前运行平台**在 `AD_UNITS` 里的池有 ID 走真机，为空走 dev 演示层），
 *     同时启用三态兜底 —— **只有完整看完才发奖**，中途关闭 / 无填充 / 未配置不发奖且给提示。
 *
 * ⚠️ 打开前置：开通流量主（**UV > 500** 且无严重违规，或"内置游戏圈 + 官方帖 5 篇"路径；资格次日刷新），
 *   并在下方 `AD_UNITS` 的**对应平台槽位**回填广告位 ID。
 * ⚠️ 本开关同时影响 **UI 文案** 与 **奖励发放路径** ⇒ 改动后需同步 DEVLOG 与验收清单。 */
export const AD_ENABLED = false;

/** 平台键（platform 层的统一寻址依据）。
 *  新增渠道时**必须先在此登记**，再在 PlatformAdapter 注册表里挂上对应宿主。 */
export type PlatformKey = 'wechat' | 'bytedance' | 'alipay' | 'h5';

/** 各平台的激励视频广告位 ID 池（**互不通用**；占位：留空即可运行，填 1 个即为单 ID 模式）。
 *
 *  为什么按平台分池：广告位 ID 是各家后台签发的**平台级凭证**，跨平台必然无效——
 *  微信的 `adunit-xxx` 拿去 `tt.createRewardedVideoAd` 只会得到 1002「广告单元无效」。
 *  所以"一维数组 + 单一适配器"的结构在多渠道下发时不成立，必须按平台寻址。
 *
 *  为什么每格是"池"而不是单个 ID：同一个广告位被反复拉取会迅速耗尽库存——
 *  官方实测约 10 次后持续返回 1004「无合适广告」，多 ID 轮换可把可用次数放大 2-3 倍。
 *  单 ID 也直接填 1 个元素，代码无需分支；空数组 = 该平台未配置。 */
